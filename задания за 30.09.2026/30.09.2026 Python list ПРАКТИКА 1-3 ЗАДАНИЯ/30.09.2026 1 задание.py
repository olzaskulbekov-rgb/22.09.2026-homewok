cities = ["Алматы", "Тараз", "Астана", "Семей"]

# Выводим результаты для проверки
print(cities[0])    # "Алматы"
print(cities[-1])   # "Семей"
print(cities[1:3])  # ["Тараз", "Астана"]
print(len(cities))  # 4
# cities[4] даёт ошибку IndexError, потому что элемента с индексом 4 не существует (индексы идут от 0 до 3).